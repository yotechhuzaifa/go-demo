// Package note contains the MongoDB-backed note domain.
//
// Notes demonstrate a document database alongside the relational task store.
// A note is a free-form annotation, optionally attached to a task. MongoDB is a
// good fit because notes are read as whole documents, their tags are naturally
// an array, and the schema is allowed to evolve without a migration.
//
// As with the task package, this package has no MongoDB imports. It defines the
// entity, validation rules, and a Repository interface; the adapter lives in
// internal/storage/mongodb.
package note

import "time"

// Note is the central entity of the note domain.
//
// ID is a UUID string rather than a MongoDB ObjectID so the API contract does
// not expose a storage-specific identifier. That keeps clients decoupled from
// the database and makes it possible to move notes later without changing URLs.
type Note struct {
	ID        string    `json:"id"`         // UUID generated by the service.
	TaskID    string    `json:"task_id"`    // Optional related task (empty when standalone).
	Author    string    `json:"author"`     // Who wrote the note; defaults to "anonymous".
	Body      string    `json:"body"`       // Required note text.
	Tags      []string  `json:"tags"`       // Optional labels; stored as a BSON array.
	CreatedAt time.Time `json:"created_at"` // UTC creation timestamp.
	UpdatedAt time.Time `json:"updated_at"` // UTC last-change timestamp.
}

// CreateInput is the data required to create a note.
type CreateInput struct {
	TaskID string   // Optional; must be a UUID when supplied.
	Author string   // Optional; defaults to "anonymous".
	Body   string   // Required.
	Tags   []string // Optional; normalized (trimmed, de-duplicated).
}

// UpdateInput describes a partial update. Nil means "leave unchanged".
//
// Tags is a pointer to a slice so an explicitly supplied empty array can clear
// all tags, which is different from omitting the field entirely.
type UpdateInput struct {
	TaskID *string
	Author *string
	Body   *string
	Tags   *[]string
}

// Filter narrows and paginates note listings.
type Filter struct {
	TaskID string // Empty means "all notes".
	Limit  int    // 0 means use the service default.
	Offset int
}
