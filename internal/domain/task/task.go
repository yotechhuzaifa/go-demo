// Package task contains the core business model and rules for tasks.
//
// This package is the "domain" layer. It deliberately has no knowledge of
// HTTP, JSON transport concerns, databases, or logging. Infrastructure
// packages depend on this package, never the other way around. That rule keeps
// business rules easy to understand and fast to test.
package task

import "time"

// Status describes where a task is in its workflow.
//
// Using a named string type (instead of a plain string) gives us compile-time
// documentation and lets us attach validation methods to it.
type Status string

// The complete set of statuses supported by the domain.
const (
	StatusTodo       Status = "todo"        // Task has not been started.
	StatusInProgress Status = "in_progress" // Task is actively being worked on.
	StatusDone       Status = "done"        // Task is complete.
)

// Valid reports whether s is one of the supported task statuses.
// An empty status is not valid here; callers decide whether empty means
// "not supplied" before validating.
func (s Status) Valid() bool {
	switch s {
	case StatusTodo, StatusInProgress, StatusDone:
		return true
	default:
		return false
	}
}

// Priority describes how urgent a task is.
type Priority string

// The complete set of priorities supported by the domain.
const (
	PriorityLow    Priority = "low"
	PriorityMedium Priority = "medium"
	PriorityHigh   Priority = "high"
)

// Valid reports whether p is one of the supported priorities.
func (p Priority) Valid() bool {
	switch p {
	case PriorityLow, PriorityMedium, PriorityHigh:
		return true
	default:
		return false
	}
}

// Task is the central entity of the application.
//
// The JSON tags live here for brevity in this sample. The HTTP layer actually
// returns a DTO (see internal/transport/httpapi/dto) so that fields such as
// due-date descriptions can be added without leaking transport concerns into
// the domain. Larger systems often keep even more distance between entities and
// wire formats, at the cost of more mapping code.
type Task struct {
	ID          string     `json:"id"`                 // UUID generated by the service.
	Title       string     `json:"title"`              // Short summary, required.
	Description string     `json:"description"`        // Optional longer text.
	Status      Status     `json:"status"`             // Workflow state.
	Priority    Priority   `json:"priority"`           // Urgency.
	DueDate     *time.Time `json:"due_date,omitempty"` // Optional absolute deadline, always UTC.
	CreatedAt   time.Time  `json:"created_at"`         // UTC creation timestamp.
	UpdatedAt   time.Time  `json:"updated_at"`         // UTC last-change timestamp.
}

// CreateInput is the data required to create a task.
//
// It is a separate type from Task because callers must not be able to choose
// fields such as ID, Status, or CreatedAt. The service owns those fields.
//
// DueDate is already parsed into a time.Time here: flexible human input such as
// "next friday" or "31/12/2026" belongs to the HTTP/date adapter, not the
// business rules. The domain only deals with unambiguous instants.
type CreateInput struct {
	Title       string     // Required; surrounding whitespace is removed.
	Description string     // Optional.
	Priority    Priority   // Optional; defaults to PriorityMedium.
	DueDate     *time.Time // Optional; normalized to UTC by the service.
}

// UpdateInput describes a partial update (HTTP PATCH semantics).
//
// A nil pointer means "leave this field unchanged". A non-nil pointer means
// "set the field to this value", including setting a string to "".
//
// DueDate is a pointer-to-pointer at the transport layer (so omitted, null, and
// a value are distinguishable). The service receives the already-resolved
// value plus ClearDueDate, which keeps this type simple and explicit.
type UpdateInput struct {
	Title        *string
	Description  *string
	Status       *Status
	Priority     *Priority
	DueDate      *time.Time
	ClearDueDate bool
}

// Filter narrows and paginates a task listing.
//
// Empty Status or Priority means "do not filter by that field".
// Limit == 0 means "use the service default"; the repository treats Limit <= 0
// as "no limit" so it can also be used directly in tests.
type Filter struct {
	Status   Status
	Priority Priority
	Limit    int
	Offset   int
}
